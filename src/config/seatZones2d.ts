export function planZonesOf(category: number): PlanZone[] {
  return PLAN_ZONES.filter((z) => z.category === category);
}

export function parsePlanPoints(points: string): [number, number][] {
  return points
    .trim()
    .split(/\s+/)
    .map((p) => p.split(',').map(Number) as [number, number]);
}
